package com.munireport.app.admin.analytics

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.munireport.app.core.utils.DateFormats
import com.munireport.app.domain.model.UserProfile
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream

/**
 * Builds the downloadable analytics snapshot. The PDF mirrors the on-screen summary
 * and contains no resident identity documents.
 */
class PdfReportExporter(
    private val context: Context,
) {
    suspend fun export(
        profile: UserProfile,
        analytics: AnalyticsUiState,
    ): File = withContext(Dispatchers.IO) {
        val directory = File(context.cacheDir, "reports").apply { mkdirs() }
        val file = File(
            directory,
            "MuniReport-analytics-${DateFormats.reportStamp(System.currentTimeMillis())}.pdf",
        )
        val document = PdfDocument()
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)
        val generatedAt = System.currentTimeMillis()

        fun header(canvas: android.graphics.Canvas, page: Int, section: String) {
            paint.color = Color.rgb(27, 94, 72)
            canvas.drawRect(0f, 0f, 595f, 10f, paint)
            paint.color = Color.rgb(28, 43, 38)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            paint.textSize = 21f
            canvas.drawText("MuniReport", 48f, 58f, paint)
            paint.typeface = Typeface.DEFAULT
            paint.textSize = 10f
            paint.color = Color.rgb(100, 112, 106)
            canvas.drawText(section, 48f, 76f, paint)
            paint.textAlign = Paint.Align.RIGHT
            canvas.drawText("Page $page", 547f, 58f, paint)
            paint.textAlign = Paint.Align.LEFT
            paint.color = Color.rgb(214, 221, 216)
            canvas.drawRect(48f, 92f, 547f, 93f, paint)
        }

        fun footer(canvas: android.graphics.Canvas) {
            paint.color = Color.rgb(120, 130, 124)
            paint.textSize = 8.5f
            canvas.drawText(
                "Generated by MuniReport for barangay operations. Report content is handled under the barangay privacy policy.",
                48f,
                822f,
                paint,
            )
        }

        fun labelValue(canvas: android.graphics.Canvas, label: String, value: String, x: Float, y: Float) {
            paint.color = Color.rgb(100, 112, 106)
            paint.textSize = 9f
            canvas.drawText(label, x, y, paint)
            paint.color = Color.rgb(28, 43, 38)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            paint.textSize = 16f
            canvas.drawText(value, x, y + 19f, paint)
            paint.typeface = Typeface.DEFAULT
        }

        val pageOne = document.startPage(PdfDocument.PageInfo.Builder(595, 842, 1).create())
        val canvasOne = pageOne.canvas
        header(canvasOne, 1, "Barangay operations snapshot")

        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 18f
        canvasOne.drawText("Operations summary", 48f, 130f, paint)
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.rgb(100, 112, 106)
        paint.textSize = 9f
        canvasOne.drawText(
            "Prepared ${DateFormats.dateTime(generatedAt)}  ·  ${profile.fullName}",
            48f,
            148f,
            paint,
        )

        labelValue(canvasOne, "TOTAL REPORTS", analytics.totalReports.toString(), 48f, 190f)
        labelValue(canvasOne, "OPEN", analytics.openReports.toString(), 230f, 190f)
        labelValue(canvasOne, "URGENT OPEN", analytics.urgentOpenReports.toString(), 400f, 190f)
        labelValue(canvasOne, "RESOLVED", analytics.resolvedReports.toString(), 48f, 255f)
        labelValue(canvasOne, "PENDING VERIFICATIONS", analytics.pendingVerifications.toString(), 230f, 255f)
        labelValue(canvasOne, "VERIFIED RESIDENTS", analytics.verifiedResidents.toString(), 400f, 255f)

        paint.color = Color.rgb(235, 241, 237)
        canvasOne.drawRoundRect(48f, 310f, 547f, 362f, 8f, 8f, paint)
        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 12f
        canvasOne.drawText("Resolution performance", 62f, 332f, paint)
        paint.typeface = Typeface.DEFAULT
        paint.textSize = 9f
        paint.color = Color.rgb(80, 94, 87)
        canvasOne.drawText(
            "${analytics.resolutionRate}% of all reports resolved  ·  Average time ${analytics.averageResolutionHours?.let(DateFormats::durationLabel) ?: "not available"}",
            62f,
            349f,
            paint,
        )
        paint.color = Color.rgb(211, 226, 217)
        canvasOne.drawRoundRect(62f, 355f, 533f, 361f, 3f, 3f, paint)
        paint.color = Color.rgb(27, 94, 72)
        canvasOne.drawRoundRect(
            62f,
            355f,
            62f + (471f * (analytics.resolutionRate.coerceIn(0, 100) / 100f)),
            361f,
            3f,
            3f,
            paint,
        )

        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 14f
        canvasOne.drawText("Reports by category", 48f, 394f, paint)
        paint.typeface = Typeface.DEFAULT
        var y = 418f
        val maxCategory = (analytics.categories.maxOfOrNull { it.count } ?: 1).coerceAtLeast(1)
        if (analytics.categories.isEmpty()) {
            paint.color = Color.rgb(100, 112, 106)
            paint.textSize = 9f
            canvasOne.drawText("No report data yet.", 48f, y, paint)
        } else {
            analytics.categories.forEach { item ->
                paint.color = Color.rgb(55, 68, 62)
                paint.textSize = 9f
                canvasOne.drawText(item.category.label, 48f, y, paint)
                paint.textAlign = Paint.Align.RIGHT
                canvasOne.drawText(item.count.toString(), 547f, y, paint)
                paint.textAlign = Paint.Align.LEFT
                paint.color = Color.rgb(235, 239, 237)
                canvasOne.drawRoundRect(48f, y + 4f, 547f, y + 9f, 2f, 2f, paint)
                paint.color = Color.rgb(27, 94, 72)
                canvasOne.drawRoundRect(
                    48f,
                    y + 4f,
                    48f + (499f * (item.count.toFloat() / maxCategory)),
                    y + 9f,
                    2f,
                    2f,
                    paint,
                )
                y += 22f
            }
        }
        paint.color = Color.rgb(100, 112, 106)
        paint.textSize = 9f
        canvasOne.drawText(
            "Closed reports are labeled as Closed in the app. Resolution time uses the most recent recorded status update.",
            48f,
            740f,
            paint,
        )
        footer(canvasOne)
        document.finishPage(pageOne)

        val pageTwo = document.startPage(PdfDocument.PageInfo.Builder(595, 842, 2).create())
        val canvasTwo = pageTwo.canvas
        header(canvasTwo, 2, "Trends and status distribution")

        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 14f
        canvasTwo.drawText("New reports · last 7 days", 48f, 132f, paint)
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.rgb(100, 112, 106)
        paint.textSize = 9f
        canvasTwo.drawText("Daily volume of concerns filed by residents", 48f, 148f, paint)

        val maxDay = (analytics.lastSevenDays.maxOfOrNull { it.count } ?: 0).coerceAtLeast(1)
        val chartBottom = 300f
        val chartTop = 178f
        analytics.lastSevenDays.forEachIndexed { index, day ->
            val columnWidth = 499f / 7f
            val left = 48f + (columnWidth * index) + 10f
            val barWidth = columnWidth - 20f
            val height = ((chartBottom - chartTop) * (day.count.toFloat() / maxDay))
                .coerceAtLeast(3f)
            paint.color = Color.rgb(235, 239, 237)
            canvasTwo.drawRoundRect(
                left,
                chartTop,
                left + barWidth,
                chartBottom,
                4f,
                4f,
                paint,
            )
            paint.color = Color.rgb(27, 94, 72)
            canvasTwo.drawRoundRect(
                left,
                chartBottom - height,
                left + barWidth,
                chartBottom,
                4f,
                4f,
                paint,
            )
            paint.color = Color.rgb(28, 43, 38)
            paint.textAlign = Paint.Align.CENTER
            paint.textSize = 10f
            canvasTwo.drawText(day.count.toString(), left + (barWidth / 2f), chartBottom - height - 7f, paint)
            paint.color = Color.rgb(100, 112, 106)
            paint.textSize = 8f
            canvasTwo.drawText(day.label, left + (barWidth / 2f), chartBottom + 16f, paint)
            paint.textAlign = Paint.Align.LEFT
        }

        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 14f
        canvasTwo.drawText("Status distribution", 48f, 370f, paint)
        paint.typeface = Typeface.DEFAULT
        var statusY = 400f
        val totalStatus = analytics.statuses.sumOf { it.count }
        analytics.statuses.forEach { item ->
            paint.color = Color.rgb(55, 68, 62)
            paint.textSize = 10f
            canvasTwo.drawText(item.status.label, 48f, statusY, paint)
            paint.textAlign = Paint.Align.RIGHT
            val share = if (totalStatus == 0) 0 else (item.count * 100) / totalStatus
            canvasTwo.drawText("${item.count} reports  ·  $share%", 547f, statusY, paint)
            paint.textAlign = Paint.Align.LEFT
            paint.color = Color.rgb(235, 239, 237)
            canvasTwo.drawRoundRect(48f, statusY + 5f, 547f, statusY + 10f, 2f, 2f, paint)
            paint.color = Color.rgb(27, 94, 72)
            canvasTwo.drawRoundRect(
                48f,
                statusY + 5f,
                48f + (499f * (share / 100f)),
                statusY + 10f,
                2f,
                2f,
                paint,
            )
            statusY += 30f
        }

        paint.color = Color.rgb(235, 241, 237)
        canvasTwo.drawRoundRect(48f, 590f, 547f, 690f, 8f, 8f, paint)
        paint.color = Color.rgb(28, 43, 38)
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 11f
        canvasTwo.drawText("How to read this snapshot", 62f, 613f, paint)
        paint.typeface = Typeface.DEFAULT
        paint.color = Color.rgb(80, 94, 87)
        paint.textSize = 9f
        canvasTwo.drawText("• Open includes Pending, Acknowledged, and In progress reports.", 62f, 633f, paint)
        canvasTwo.drawText("• Resolution rate is resolved reports divided by all reports.", 62f, 650f, paint)
        canvasTwo.drawText("• No resident identity documents are included in this export.", 62f, 667f, paint)
        footer(canvasTwo)
        document.finishPage(pageTwo)

        FileOutputStream(file).use(document::writeTo)
        document.close()
        file
    }
}
